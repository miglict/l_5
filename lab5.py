import random  # подключаем рандом, чтобы заполнить матрицу

# просим размер матрицы (она квадратная, поэтому нужно одно число)
n = int(input("Введите размер матрицы n: "))

# создаем пустую матрицу (список списков)
matrix = []

# заполняем матрицу случайными целыми числами от -5 до 10
for i in range(n):
    row = []  # создаем пустую строку
    for j in range(n):
        row.append(random.randint(-5, 10))  # добавляем случайное число
    matrix.append(row)  # добавляем строку в матрицу

# выводим матрицу на экран, чтобы было видно, с чем работаем
print("\nНаша матрица:")
for row in matrix:
    print(row)

print("\n--- Пункт 1 ---")
total_sum = 0  # общая сумма для подходящих столбцов

for j in range(n):  # перебираем столбцы (j - номер столбца)
    has_negative = False  # флаг: есть ли в столбце отрицательные числа?

    # проходим по всем строкам в текущем столбце
    for i in range(n):
        if matrix[i][j] < 0:  # если нашли отрицательное число
            has_negative = True  # ставим флаг
            break  # дальше этот столбец можно не проверять

    # если отрицательных не нашли, считаем сумму этого столбца
    if not has_negative:
        col_sum = 0
        for i in range(n):
            col_sum += matrix[i][j]
        total_sum += col_sum  # прибавляем к общей сумме
        print(f"Столбец {j} подходит, его сумма = {col_sum}")

print(f"Общая сумма: {total_sum}")

print("\n--- Пункт 2 ---")

min_sum = None  # тут будем хранить минимум. Пока ничего нет.

# k меняется от 0 до 2*n - 2
for k in range(2 * n - 1):
    diag_sum = 0  # сумма модулей элементов на текущей диагонали

    # проходим по строкам
    for i in range(n):
        j = k - i  # если i + j = k, то j = k - i
        # проверяем, что j не вылез за пределы матрицы (от 0 до n-1)
        if 0 <= j < n:
            diag_sum += abs(matrix[i][j])  # прибавляем модуль элемента

    # выводим сумму для текущей диагонали (для наглядности)
    print(f"Диагональ k={k}, сумма модулей = {diag_sum}")

    # если это первая посчитанная диагональ или она меньше текущего минимума
    if min_sum is None or diag_sum < min_sum:
        min_sum = diag_sum

print(f"Минимум среди сумм: {min_sum}")